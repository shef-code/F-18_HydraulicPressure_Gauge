# Generates GaugeGlyphs.h: a tiny anti-aliased (8-bit alpha) glyph atlas used by the procedural gauge style.
# Only the characters the gauge needs are included.
# Run:  powershell -ExecutionPolicy Bypass -File tools\render_glyph_atlas.ps1
Add-Type -AssemblyName System.Drawing
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
# MS33558 (MIL-STD aircraft instrument dial lettering). Installed per-user, so load the file directly.
# Its em height equals its cap height, so px below is the cap height in dial pixels.
$FONTFILE = Join-Path $env:LOCALAPPDATA 'Microsoft\Windows\Fonts\MS33558.ttf'
$pfc = New-Object System.Drawing.Text.PrivateFontCollection; $pfc.AddFontFile($FONTFILE)
$FAMILY = $pfc.Families[0]
$K = 8                                   # supersampling

$fonts = @(
  @{ name='Numerals'; px=20; track=0; chars='012345'  },   # scale numerals + needle tags
  @{ name='Legend';   px=22; track=1; chars='HYDPRES ' },  # HYD PRESS
  @{ name='Small';    px=16; track=1; chars='PSIX01 ' }    # PSI X 1000
)

$fmt = [System.Drawing.StringFormat]::GenericTypographic.Clone()
$fmt.FormatFlags = $fmt.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces
$mb = New-Object System.Drawing.Bitmap 8,8; $mg = [System.Drawing.Graphics]::FromImage($mb)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Anti-aliased glyph atlas (8-bit alpha) for the procedural gauge style.')
[void]$sb.AppendLine('// Generated by tools/render_glyph_atlas.ps1 - do not edit by hand.')
[void]$sb.AppendLine('#pragma once'); [void]$sb.AppendLine('#include <Arduino.h>'); [void]$sb.AppendLine()
[void]$sb.AppendLine('struct GGlyph { char c; uint8_t w, h; int8_t xo, yo; uint8_t adv; uint16_t off; };')
[void]$sb.AppendLine('struct GFont  { const GGlyph* glyphs; uint8_t count; uint8_t capH; const uint8_t* data; };'); [void]$sb.AppendLine()

foreach($f in $fonts){
  $em = $f.px * $K
  $asc = $FAMILY.GetCellAscent([System.Drawing.FontStyle]::Regular) / $FAMILY.GetEmHeight([System.Drawing.FontStyle]::Regular) * $em
  $data = New-Object 'System.Collections.Generic.List[int]'
  $rows = @(); $capH = 0
  foreach($ch in $f.chars.ToCharArray()){
    $s = [string]$ch
    $adv = [math]::Round($mg.MeasureString($s, (New-Object System.Drawing.Font $FAMILY,([single]$em),([System.Drawing.FontStyle]::Regular),([System.Drawing.GraphicsUnit]::Pixel)), 10000, $fmt).Width / $K)
    if($ch -eq " "){ $adv = [math]::Round($f.px * 0.4) }   # MS33558 word space is a full em; tighten it
    $adv += $f.track
    if($ch -eq ' '){ $rows += "{ ' ', 0, 0, 0, 0, $adv, $($data.Count) }"; continue }
    $path = New-Object System.Drawing.Drawing2D.GraphicsPath
    $path.AddString($s, $FAMILY, [int][System.Drawing.FontStyle]::Regular, [single]$em, [System.Drawing.PointF]::new(0,0), $fmt)
    $b = $path.GetBounds()
    $x0 = [math]::Floor($b.Left / $K); $y0 = [math]::Floor(($b.Top - $asc) / $K)
    $w1 = [math]::Ceiling($b.Right / $K) - $x0; $h1 = [math]::Ceiling(($b.Bottom - $asc) / $K) - $y0
    if(($b.Top - $asc) -lt 0 -and (-($b.Top - $asc) / $K) -gt $capH){ $capH = [math]::Round(-($b.Top - $asc) / $K) }
    $bmp = New-Object System.Drawing.Bitmap ($w1*$K),($h1*$K), ([System.Drawing.Imaging.PixelFormat]::Format24bppRgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp); $g.Clear([System.Drawing.Color]::Black); $g.SmoothingMode='AntiAlias'
    $m = New-Object System.Drawing.Drawing2D.Matrix; $m.Translate([single](-$x0*$K), [single](-$asc - $y0*$K)); $path.Transform($m)
    $g.FillPath([System.Drawing.Brushes]::White, $path); $g.Dispose()
    $bd = $bmp.LockBits([System.Drawing.Rectangle]::new(0,0,$bmp.Width,$bmp.Height), 'ReadOnly', $bmp.PixelFormat)
    $raw = New-Object byte[] ($bd.Stride * $bmp.Height); [System.Runtime.InteropServices.Marshal]::Copy($bd.Scan0, $raw, 0, $raw.Length); $bmp.UnlockBits($bd)
    $off = $data.Count
    for($y=0;$y -lt $h1;$y++){ for($x=0;$x -lt $w1;$x++){
      $sum = 0
      for($j=0;$j -lt $K;$j++){ $rowBase = ($y*$K+$j)*$bd.Stride + ($x*$K)*3; for($i=0;$i -lt $K;$i++){ $sum += $raw[$rowBase + $i*3] } }
      $data.Add([int][math]::Round($sum / ($K*$K)))
    } }
    $bmp.Dispose()
    $rows += "{ '$s', $w1, $h1, $x0, $y0, $adv, $off }"
  }
  [void]$sb.AppendLine("const GGlyph glyphs$($f.name)[] = {")
  foreach($r in $rows){ [void]$sb.AppendLine("  $r,") }
  [void]$sb.AppendLine('};')
  [void]$sb.AppendLine("const uint8_t glyphData$($f.name)[] = {")
  for($i=0;$i -lt $data.Count;$i+=32){ $e=[math]::Min($i+32,$data.Count)-1; [void]$sb.AppendLine('  ' + (($data[$i..$e] | ForEach-Object { $_.ToString() }) -join ',') + ',') }
  [void]$sb.AppendLine('};')
  [void]$sb.AppendLine("const GFont font$($f.name) = { glyphs$($f.name), $($rows.Count), $capH, glyphData$($f.name) };"); [void]$sb.AppendLine()
}
[IO.File]::WriteAllText((Join-Path $root 'GaugeGlyphs.h'), $sb.ToString())
Write-Host 'GaugeGlyphs.h written'
